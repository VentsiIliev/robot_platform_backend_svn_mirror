#!/usr/bin/env bash
# Configure the existing Ubuntu 24.04 GDM installation; never restart GDM here.
set -euo pipefail
usage() {
  cat <<'EOF'
Usage:
  sudo ./setup_kiosk.sh install --user USER --directory DIR [options] -- COMMAND [ARGS...]
  sudo ./setup_kiosk.sh uninstall --user USER
Options:
  --autologin yes|no       Default: no (test manual login first)
  --restart failure|always Default: failure (successful exit logs out)
  --delay SECONDS          Default: 5 (minimum 1)
  --help
Example:
  sudo ./setup_kiosk.sh install --user pl_user --directory "$PWD" -- ./launch_robot_app.sh
EOF
}
die() { echo "$*" >&2; exit 1; }
action=${1:-}; [[ $# -eq 0 ]] || shift
if [[ $action == --help || $action == -h ]]; then usage; exit 0; fi
user= directory= autologin=no restart=failure delay=5
while [[ $# -gt 0 ]]; do
  case "$1" in
    --help|-h) usage; exit 0 ;;
    --) shift; break ;;
    --user|--directory|--autologin|--restart|--delay)
      [[ $# -ge 2 ]] || die "Missing value for $1"
      case "$1" in
        --user) user=$2 ;; --directory) directory=$2 ;;
        --autologin) autologin=$2 ;; --restart) restart=$2 ;; --delay) delay=$2 ;;
      esac
      shift 2 ;;
    *) usage; die "Unknown option: $1" ;;
  esac
done
[[ $action == install || $action == uninstall ]] || { usage; exit 2; }
[[ $EUID -eq 0 ]] || die "Run with sudo."
[[ $user =~ ^[a-z_][a-z0-9_-]*\$?$ && $user != root ]] || die "Specify an existing non-root --user."
entry=$(getent passwd "$user") || die "Unknown account: $user"
IFS=: read -r _ _ uid gid _ user_home _ <<< "$entry"
[[ -d $user_home ]] || die "Account home does not exist."
source /etc/os-release
[[ $ID == ubuntu && $VERSION_ID == 24.04 ]] || die "Supported target: Ubuntu 24.04."
[[ -f /etc/gdm3/custom.conf ]] || die "GDM3 configuration is missing."
[[ $(cat /etc/X11/default-display-manager) == /usr/sbin/gdm3 ]] || die "GDM3 must be the active display manager."
state=/var/lib/platform-kiosk/$user
script=$user_home/.local/bin/gnome-kiosk-script
account=/var/lib/AccountsService/users/$user

if [[ $action == install ]]; then
  [[ $autologin == yes || $autologin == no ]] || die "--autologin must be yes or no."
  [[ $restart == failure || $restart == always ]] || die "--restart must be failure or always."
  [[ $delay =~ ^[0-9]+$ && ${#delay} -le 4 ]] || die "--delay must be 1..9999."
  ((10#$delay >= 1)) || die "--delay must be at least 1."
  [[ $directory == /* && -d $directory && $# -gt 0 ]] || die "Provide an absolute --directory and a command after --."
  runuser -u "$user" -- test -x "$directory" || die "User cannot access working directory."
  executable=$1
  if [[ $executable == */* ]]; then
    [[ $executable == /* ]] || executable=$directory/$executable
    runuser -u "$user" -- test -x "$executable" || die "Launcher is not executable for $user: $executable"
  else
    runuser -u "$user" -- sh -c 'command -v "$1" >/dev/null' sh "$executable" || die "Command not found for $user: $executable"
  fi
  apt-get update
  # Fresh desktops may still be installing unattended updates.
  apt-get -o DPkg::Lock::Timeout=600 install -y gnome-kiosk gnome-kiosk-script-session
  [[ -f /usr/share/xsessions/gnome-kiosk-script-xorg.desktop ]] || die "X11 kiosk session is missing."
  install -d -m 700 "$state"
  # Preserve the original baseline across repeated installs.
  if [[ ! -f $state/complete ]]; then
    for name in gdm account script; do
      case $name in gdm) path=/etc/gdm3/custom.conf ;; account) path=$account ;; script) path=$script ;; esac
      if [[ -e $path ]]; then cp -a "$path" "$state/$name"; else touch "$state/$name.absent"; fi
    done
    touch "$state/complete"
  fi
  install -d -o "$uid" -g "$gid" "$user_home/.local/bin" "$user_home/.local/state/robot-kiosk"
  {
    printf '#!/usr/bin/env bash\n# Generated by setup_kiosk.sh\n'
    printf 'exec >> %q 2>&1\n' "$user_home/.local/state/robot-kiosk/session.log"
    printf 'cd %q || exit 1\n' "$directory"
    printf 'while true; do\n  '
    printf '%q ' "$@"
    printf '\n  status=$?\n'
    if [[ $restart == failure ]]; then
      printf '  if [[ $status -eq 0 ]]; then\n    gnome-session-quit --logout --no-prompt\n    exit 0\n  fi\n'
    fi
    printf '  sleep %q\ndone\n' "$delay"
  } > "$script"
  chown "$uid:$gid" "$script"
  chmod 755 "$script"
  python3 - "$account" "$user" "$autologin" <<'PY'
import configparser
import pathlib
import sys
account, user, autologin = sys.argv[1:]
def update(path, section, values):
    path = pathlib.Path(path)
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    parser.read(path)
    if not parser.has_section(section):
        parser.add_section(section)
    for key, value in values.items():
        # Replace case variants too, as GDM treats option names case insensitively.
        for existing in list(parser[section]):
            if existing.lower() == key.lower():
                parser.remove_option(section, existing)
        parser.set(section, key, value)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w') as output:
        parser.write(output, space_around_delimiters=False)
update(account, 'User', {'Session': 'gnome-kiosk-script-xorg',
                        'XSession': 'gnome-kiosk-script-xorg', 'SessionType': 'x11'})
update('/etc/gdm3/custom.conf', 'daemon', {'WaylandEnable': 'false',
       'AutomaticLoginEnable': str(autologin == 'yes'), 'AutomaticLogin': user,
       'TimedLoginEnable': 'False'})
PY
  echo "Configured. Log out and select Kiosk Script Session (X11 Display Server)."
  echo "Automatic login: $autologin. Reboot when ready; no session was stopped."
else
  [[ -f $state/complete ]] || die "No installer backup exists for $user."
  [[ $# -eq 0 ]] || die "Uninstall does not accept a command."
  for name in gdm account script; do
    case $name in gdm) path=/etc/gdm3/custom.conf ;; account) path=$account ;; script) path=$script ;; esac
    if [[ -f $state/$name.absent ]]; then
      rm -f -- "$path"
    else
      cp -a "$state/$name" "$path"
    fi
  done
  echo "Original configuration restored. Packages and logs retained. Reboot when ready."
fi
